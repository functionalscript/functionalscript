/**
 * The fixture every B-tree proof shares: a string B-tree ordered by `cmp`,
 * the squares corpus built in it, and the shapes that corpus takes as it
 * grows.
 *
 * @module
 *
 * @import { Unknown } from '../../media/json/types.ts'
 * @import { TNode } from './types/types.ts'
 */

import { stringify } from '../../media/json/module.f.mjs'
import { sort } from '../object/module.f.mjs'
import { cmp } from '../string/module.f.mjs'
import { set as setSet } from './set/module.f.mjs'

/**
 * Serializes a tree canonically, so a proof compares its shape as a string.
 *
 * @type {(value: Unknown) => string}
 */
export const jsonStr = stringify(sort)

/**
 * Inserts `value` into a string B-tree ordered by `cmp`, the shape every
 * B-tree proof tests.
 *
 * @type {(node: TNode<string>) => (value: string) => TNode<string>}
 */
export const set = node => value => setSet(cmp(value))(() => value)(node)

/**
 * `['1']` with the squares of `2..n` inserted, in that order: the shared
 * corpus.
 *
 * @type {(n: number) => TNode<string>}
 */
export const squares = n => n <= 1 ? ['1'] : set(squares(n - 1))((n * n).toString())

