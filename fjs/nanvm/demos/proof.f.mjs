/**
 * Proofs for the WASM demo samples' generator: samples in the virtual
 * filesystem, compiled, and the outputs read back.
 *
 * @import { Dir } from '../../effects/node/virtual/types.ts'
 */

import { assert, assertEq, assertOk } from '../../asserts/module.f.js'
import { exitCode, readUtf8File } from '../../effects/node/module.f.mjs'
import { defaultNodeProgramOptions, emptyState, virtual, virtualAt } from '../../effects/node/virtual/module.f.mjs'
import { utf8 } from '../../text/module.f.mjs'
import { callStatement, f64Literal, generate, main, modules, modulesPath, rustPath, samplePath, samples } from './module.f.mjs'

/** @type {(samples: Dir) => Dir} */
const at = samples => ({ 'fjs': { 'nanvm': { 'demos': samples } } })

/** Two samples, and a directory that is not one. @type {Dir} */
const root = at({
    'a': { 'sample.f.js': [utf8('export default () => 1;')] },
    'b': { 'sample.f.js': [utf8('export default () => 2;')] },
    'c': { 'README.md': [utf8('# not a sample')] },
})

export const proof = {
    samplePath: () => assertEq(samplePath('fjs/nanvm/demos/hello'), 'fjs/nanvm/demos/hello/sample.f.js'),
    // A sample of its own beside the generator, a spec page's example beside its page.
    samples: () => {
        assertEq(
            samples.slice(0, 4).map(({ name, directory }) => `${name}:${directory}`).join(','),
            'hello:fjs/nanvm/demos/hello,sort:fjs/nanvm/demos/sort,collatz:fjs/nanvm/demos/collatz,comma:spec/operators/comma')
        // Every other sample is a spec page's example.
        assert(samples.slice(4).every(({ directory }) => directory.startsWith('spec/')))
    },
    // In `rustfmt`'s order, not the list's.
    modules: () => assertEq(modules([{ name: 'b', directory: 'b' }, { name: 'a', directory: 'a' }]), [
        '// @generated by `fjs run ./fjs/nanvm/demos/module.f.mjs`. Do not edit: add or remove a sample instead.',
        '',
        'pub mod a;',
        'pub mod b;',
        '',
        '/// Loads the `a` sample.',
        '#[unsafe(no_mangle)]',
        'pub extern "C" fn a() -> i32 {',
        '    crate::export(a::module::<nanvm_lib::naive::Naive>)',
        '}',
        '',
        '/// Loads the `b` sample.',
        '#[unsafe(no_mangle)]',
        'pub extern "C" fn b() -> i32 {',
        '    crate::export(b::module::<nanvm_lib::naive::Naive>)',
        '}',
        '',
    ].join('\n')),
    // A function sample's calls are a test, each call a statement.
    tests: () => assertEq(modules([{ name: 'f', directory: 'f', calls: [[1, ['returned', '3']], [-0.5, ['threw', '"x"']]] }]).split('\n').slice(-13).join('\n'), [
        '/// The calls each function sample lists, each answered as JavaScript answers it.',
        '#[cfg(test)]',
        'mod tests {',
        '    use nanvm_lib::naive::Naive;',
        '',
        '    #[test]',
        '    fn f() {',
        '        let entry = crate::load(super::f::module::<Naive>).unwrap();',
        '        crate::assert_call(&entry, 1.0, Ok("3"));',
        '        crate::assert_call(&entry, -0.5, Err("\\"x\\""));',
        '    }',
        '}',
        '',
    ].join('\n')),
    f64Literal: () => assertEq([1, -42.5, 0].map(f64Literal).join(' '), '1.0 -42.5 0.0'),
    // Arguments wider than `rustfmt`'s 60 characters, one a line.
    callStatement: () => {
        assertEq(callStatement([1, ['returned', '3']]).length, 1)
        assertEq(callStatement([1, ['returned', 'x'.repeat(60)]]).join('\n'), [
            '        crate::assert_call(',
            '            &entry,',
            '            1.0,',
            `            Ok("${'x'.repeat(60)}"),`,
            '        );',
        ].join('\n'))
        // A lone surrogate has no `&str`.
        assert(callStatement([1, ['returned', '\ud800']])[0].includes('"(not UTF-8)"'))
    },
    // The listed samples only, then `mod.rs` naming them.
    generate: () => {
        const [state, result] = virtualAt(root)(generate([{ name: 'a', directory: 'fjs/nanvm/demos/a' }, { name: 'b', directory: 'fjs/nanvm/demos/b' }]))
        assertOk(result)
        const [, modRs] = virtual(state)(readUtf8File(modulesPath))
        assertEq(assertOk(modRs), modules([{ name: 'a', directory: 'fjs/nanvm/demos/a' }, { name: 'b', directory: 'fjs/nanvm/demos/b' }]))
        const [, aRs] = virtual(state)(readUtf8File(rustPath('a')))
        assert(assertOk(aRs).startsWith('// @generated by `fjs compile`.'))
    },
    // A sample the compiler refuses stops the sequence before `mod.rs` is
    // written: a list naming a module that does not exist would not build.
    generateStopsAtARefusedSample: () => {
        const broken = at({ 'a': { 'sample.f.js': [utf8('export default (')] } })
        const [state, result] = virtualAt(broken)(generate([{ name: 'a', directory: 'fjs/nanvm/demos/a' }]))
        assertEq(result[0], 'error')
        assertEq(virtual(state)(readUtf8File(modulesPath))[1][0], 'error')
    },
    // A listed sample with no source is the failure `fjs run` reports.
    main: () => {
        const [state, code] = virtual(emptyState)(main(defaultNodeProgramOptions))
        assertEq(exitCode(code), 1)
        assert(state.stderr !== '')
    },
}
