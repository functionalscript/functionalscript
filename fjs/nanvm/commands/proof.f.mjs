import { assert, assertEq } from '../../asserts/module.f.js'
import { nodeCommands } from '../../effects/node/module.f.mjs'
import { generate, path } from './module.f.mjs'
import { occurrences } from '../../types/string/module.f.mjs'

export const proof = {
    generate: () => {
        const rust = generate()
        assert(rust.startsWith('// @generated by `npm run gen` from `fjs/nanvm/commands/module.f.mjs`. Do not edit: `nodeCommands` in `fjs/effects/node/module.f.mjs` is the source.\n\n'), rust)
        assert(rust.includes('pub const COMMANDS: &[&str] = &[\n    "access",\n'), rust)
        assert(rust.endsWith('    "writeFile",\n];\n'), rust)
        // Every command of the set is printed once, and nothing else is.
        assertEq(occurrences('\n    "')(rust), nodeCommands.length)
        assert(nodeCommands.every(command => rust.includes(`\n    "${command}",\n`)), rust)
        assertEq(path, 'nanvm/effects-node/src/gen.commands.rs')
    },
}
