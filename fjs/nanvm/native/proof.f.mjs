import { assert, assertEq } from '../../asserts/module.f.mjs'
import { generate, path } from './module.f.mjs'

export const proof = {
    generate: () => {
        const rust = generate()
        assert(rust.startsWith('// @generated by `npm run gen` from `fjs/nanvm/native/module.f.mjs`. Do not edit: `entriesText` in `fjs/edag/value/entries/module.f.mjs` is the source.\n\n'), rust)
        assert(rust.endsWith('\npub const ENTRIES_TEXT: &str = "a => Object.entries(a)";\n'), rust)
        assertEq(path, 'nanvm/lib/src/vm/gen.native.rs')
    },
}
