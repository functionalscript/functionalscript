/**
 * Proofs for the generated-Rust writer.
 *
 * @import { IoChannel, ReadFile } from '../../effects/node/types.ts'
 * @import { Effect } from '../../effects/types.ts'
 * @import { Dir } from '../../effects/node/virtual/types.ts'
 */

import { exitCode } from '../../effects/node/module.f.mjs'
import { assert, assertEq, assertOk } from '../../asserts/module.f.mjs'
import { pureOk, step as ioStep } from '../../effects/module.f.mjs'
import { readUtf8File } from '../../effects/node/module.f.mjs'
import {
    defaultNodeProgramOptions,
    emptyState,
    virtual,
    virtualAt,
} from '../../effects/node/virtual/module.f.mjs'
import { data } from '../module.f.mjs'
import { directory, generate } from '../rust/module.f.mjs'
import { generate as generateCommands, path as commandsPath } from '../commands/module.f.mjs'
import { generate as generateMethods, path as methodsPath } from '../methods/module.f.mjs'
import { generate as generateNative, path as nativePath } from '../native/module.f.mjs'
import { generate as generateValues, path as valuesPath } from '../values/module.f.mjs'
import { edagPath, rustPath } from '../runtime/module.f.mjs'
import { utf8 } from '../../text/module.f.mjs'
import { generateRustTests, main } from './module.f.mjs'

/** A stand-in for `fjs/js/runtime` at its path, for the compiles the writer ends with. @type {Dir} */
const root = { 'fjs': { 'js': { 'runtime': { 'module.f.js': [utf8('export const runtime = {};')] } } } }

export const proof = {
    generateRustTests: () => {
        // The target directory does not exist in `emptyState`, so this also
        // covers the `mkdir` the writer does before the file write.
        // Written once, then every file read back as it was printed.
        const files = generate(data)
        /** @type {Effect<ReadFile, readonly string[], IoChannel>} */
        const readAll = files.reduce(
            (/** @type {Effect<ReadFile, readonly string[], IoChannel>} */ e, [name]) =>
                ioStep(e, read => ioStep(readUtf8File(`${directory}/${name}`), c => pureOk([...read, c]))),
            pureOk([]))
        const [written, [tag, result]] = virtualAt(root)(ioStep(generateRustTests(), () => readAll))
        assert(tag === 'ok', result)
        assertEq(result.length, files.length)
        files.forEach(([, content], i) => { assertEq(result[i], content) })
        const table = ioStep(generateRustTests(), () => readUtf8File(methodsPath))
        const [, [tableTag, tableResult]] = virtualAt(root)(table)
        assert(tableTag === 'ok', tableResult)
        assertEq(tableResult, generateMethods())
        const [, nativeResult] = virtual(written)(readUtf8File(nativePath))
        assertEq(assertOk(nativeResult), generateNative())
        const [, valuesResult] = virtual(written)(readUtf8File(valuesPath))
        assertEq(assertOk(valuesResult), generateValues())
        const [, commandsResult] = virtual(written)(readUtf8File(commandsPath))
        assertEq(assertOk(commandsResult), generateCommands())
        // the runtime, compiled last: Rust for the VM and EDAG for the corpus proof
        const [, rustResult] = virtual(written)(readUtf8File(rustPath))
        assert(assertOk(rustResult).startsWith('// @generated by `fjs compile`.'))
        const [, edagResult] = virtual(written)(readUtf8File(edagPath))
        assertEq(assertOk(edagResult), 'export default ["{}",[[":","runtime",["{}",[]]]]];')
    },
    // No runtime source to compile is the writer's failure.
    generateRustTestsWithoutARuntime: () => {
        const [, result] = virtual(emptyState)(generateRustTests())
        assertEq(result[0], 'error')
    },
    main: () => {
        const [, result] = virtualAt(root)(main(defaultNodeProgramOptions))
        assertEq(exitCode(result), 0)
    },
}
