/**
 * Proofs for Rust items spelled over strings.
 */

import { assertEq, assertStructurallySame } from '../../../asserts/module.f.js'
import { error, ok } from '../../../types/result/module.f.js'
import { stringLiteral } from '../module.f.mjs'
import { constSlice, generatedHeader, indent } from './module.f.js'

export const proof = {
    indent: () => assertEq(indent, '    '),
    constSlice: {
        // One row per line, in the order given, each indented with its comma.
        rows: () => assertStructurallySame(
            constSlice('Names.', 'NAMES', '&str', ['b', 'a\\"'], stringLiteral),
            ok([
                '/// Names.',
                '#[rustfmt::skip]',
                'pub const NAMES: &[&str] = &[',
                '    "b",',
                '    "a\\\\\\"",',
                '];',
            ].join('\n'))),
        // A row keeps the caller's own type; the formatter spells it.
        pairs: () => assertStructurallySame(
            constSlice('Pairs.', 'PAIRS', '(&str, u8)', [['x', 1]], ([s, n]) => ok(`("${s}", ${n})`)),
            ok('/// Pairs.\n#[rustfmt::skip]\npub const PAIRS: &[(&str, u8)] = &[\n    ("x", 1),\n];')),
        empty: () => assertStructurallySame(
            constSlice('None.', 'NONE', '&str', [], stringLiteral),
            ok('/// None.\n#[rustfmt::skip]\npub const NONE: &[&str] = &[\n];')),
        // The first refusal is the answer, in row order: nothing is dropped.
        refusal: () => {
            assertStructurallySame(constSlice('N.', 'N', '&str', ['a', '\ud800', '\udc00'], stringLiteral), error('\ud800'))
            assertStructurallySame(
                constSlice('N.', 'N', '&str', ['a', 'b'], s => s === 'a' ? ok('"a"') : error(`refused ${s}`)),
                error('refused b'))
        },
    },
    generatedHeader: () => assertEq(
        generatedHeader('`npm run gen` from `x`', 'change `y` instead'),
        '// @generated by `npm run gen` from `x`. Do not edit: change `y` instead.'),
}
