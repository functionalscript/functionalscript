/**
 * Rust items spelled over strings.
 *
 * The layer one above the literals of [`fjs/media/rust`](../module.f.mjs)
 * and below any printer: an item several generators write — a `const`
 * table, the header that says a file is generated — spelled once, over the
 * text its caller has already spelled. It takes no `Exp`, so a generator of
 * a few quoted rows imports it without importing the EDAG; the items that do
 * take one stay with the printer, `fjs/edag/rust`.
 *
 * @module
 *
 * @import { Result } from '../../../types/result/types.ts'
 */

import { mapOk, okList } from '../../../types/result/module.f.js'

/**
 * The indentation of one level of generated Rust: a scope's statements
 * inside their function, a block's lines inside its braces, a table's rows
 * inside its slice.
 */
export const indent = '    '

/**
 * A documented `pub const` slice, one row per line in the order given, or
 * the first refusal of `formatRow`. `type` is the element type, `doc` one
 * line of documentation, and `formatRow` spells one element expression,
 * without indentation or a trailing comma, refusing a row it cannot spell —
 * a name `fjs/media/rust`'s `stringLiteral` refuses, say — so no row is
 * dropped or written as Rust that does not compile.
 *
 * The slice carries `#[rustfmt::skip]`: its layout is one row per line,
 * which `rustfmt` would pack.
 *
 * @type {<T, E>(doc: string, name: string, type: string, rows: readonly T[], formatRow: (row: T) => Result<string, E>) => Result<string, E>}
 */
export const constSlice = (doc, name, type, rows, formatRow) => mapOk((/** @type {readonly string[]} */ items) => [
    `/// ${doc}`,
    '#[rustfmt::skip]',
    `pub const ${name}: &[${type}] = &[`,
    ...items.map(item => `${indent}${item},`),
    '];',
].join('\n'))(okList(rows.map(formatRow)))

/**
 * The comment line a generated file opens with: what generated it and what
 * to do instead of editing it, `// @generated by …. Do not edit: ….`,
 * without the newline or the blank line after, which are the caller's.
 *
 * One line, as `fjs compile` has always written it: a reader — the corpus
 * expectations' `fjs/nanvm/expected` among them — replaces a generated
 * module's header by replacing its first line.
 *
 * @type {(source: string, instruction: string) => string}
 */
export const generatedHeader = (source, instruction) =>
    `// @generated by ${source}. Do not edit: ${instruction}.`
