/** @type {Type} */
const sumType = ['sum', [['a', unit], ['b', f64]]]

/**
 * What only the printer reads, as the checker refuses most of it: the
 * other shapes of types, the other floats, terms whose parts need lines of
 * their own, a call of another module, and a name for an arm's operand.
 *
 * @type {Module}
 */
const zoo = {
    functions: [
        ['ranges', fn([['a', int(-5n, -1n)], ['b', int(0n, 0n)], ['c', int(1n, 3n)]], f64, lit(f64, 1.5))],
        ['shapes', fn([['p', ['product', [['a', f64], ['b', bool]]]], ['s', sumType]], unit, make([]))],
        ['floats', fn([], f64, add(add(lit(f64c, -0), lit(f64c, NaN)), add(lit(f64c, Infinity), add(lit(f64c, -Infinity), add(lit(f64c, 1e21), lit(f64c, -2))))))],
        ['spread', fn([], f64, add(let_('x', n(1n), x => x), n(2n)))],
        ['fields', fn([], unit, make([['a', n(1n)], ['b', let_('x', n(2n), x => x)]]))],
        ['flatFields', fn([['x', f64]], unit, make([['a', n(1n)], ['b', get('x')]]))],
        ['other', fn([], f64, call('m', 'f', [n(1n)]))],
        ['unitBlock', fn([], unit, block('l', unit, br('l', let_('x', n(1n), x => x))))],
        ['blockValue', fn([], f64, let_('x', block('l', f64, n(1n)), x => x))],
        ['ifLet', fn([], f64, if_(let_('c', true_, c => c), n(1n), n(2n)))],
        ['binder', fn([['s', sumType]], f64, s => match(s, [[['a', 'b'], 'x', n(1n)], [null, null, n(2n)]]))],
        ['bare', fn([], bool, true_)],
        ['nested', fn([], f64, add(add(let_('x', n(1n), x => x), n(2n)), n(3n)))],
        ['payload', fn([], bool, let_('u', make([]), u => let_('b', variant(bool, 'true', u), b => b)))],
        ['brLet', fn([], f64, block('l', f64, if_(true_, br('l', let_('x', n(1n), x => x)), n(2n))))],
    ],
    exports: [],
}

