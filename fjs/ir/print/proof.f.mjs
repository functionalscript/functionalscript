        assertEq(show(int(-0x80n, 0x80n)), 'int(-128, 128)')
        assertEq(show(f64c), 'f64c')
        assertEq(show(unit), 'unit')
        assertEq(show(never), 'never')
        assertEq(show(bool), 'bool')
        assertEq(show(sumType), 'sum({ a: unit, b: f64 })')
