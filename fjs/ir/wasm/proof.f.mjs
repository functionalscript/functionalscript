/** @type {(m: Module) => ReturnType<typeof emit>} */
const emitted = m => emit(assertOk(check(m)))

/** The instructions of a module's first function, one after another. @type {(m: Module) => string} */
const body = m => emitted(m).functions[0].body.map(x => x.join(' ')).join(', ')

/**
 * The instructions of `f(a, b) = name(a, b)`, or of `f(a) = name(a)`
 * where `b` is `null`.
 *
 * @type {(name: OpName, a: Type, b: Type | null, result: Type) => string}
 */
const op = (name, a, b, result) => {
    /** @type {readonly Param[]} */
    const params = b === null ? [['a', a]] : [['a', a], ['b', b]]
    /** @type {Term} */
    const t = ['op', name, params.map(([k]) => get(k))]
    return body({ functions: [['f', fn(params, result, t)]], exports: [] })
}

