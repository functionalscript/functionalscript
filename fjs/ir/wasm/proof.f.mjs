        // and result fit 32 bits, and 64 bits where one of them does not.
        assertEq(op('add', u(8), u(8), int(0n, 0x1fen)), 'local.get 0, local.get 1, i32.add')
        assertEq(op('add', u(32), u(8), u(33)), 'local.get 0, i64.extend_i32_u, local.get 1, i64.extend_i32_u, i64.add')
        assertEq(op('sub', i(8), i(8), int(-0xffn, 0xffn)), 'local.get 0, local.get 1, i32.sub')
        assertEq(op('sub', i(32), u(8), i(64)), 'local.get 0, i64.extend_i32_s, local.get 1, i64.extend_i32_u, i64.sub')
