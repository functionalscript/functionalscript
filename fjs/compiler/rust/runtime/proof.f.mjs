/** @import { Exp } from '../../../edag/types.ts' */
import { assert, assertEq, assertError, assertOk } from '../../../asserts/module.f.mjs'
import { fromTagged } from '../../../text/marked/module.f.mjs'
import runtime from '../../../js/runtime/gen.edag.data.mjs'
import { generateRuntime, generateRuntimeTagged } from './module.f.mjs'

/** A function node: its length, slots and body. @type {(length: number, slots: readonly Exp[], body: Exp) => Exp} */
const fn = (length, slots, body) => ['=>', length, slots, body]

/** A runtime module's export object, its `runtime` export the sections given. @type {(sections: readonly (readonly [string, Exp])[]) => Exp} */
const module = sections => ['{}', [[':', 'runtime', ['{}', sections.map(([name, value]) => [':', name, value])]]]]

/** An object literal node. @type {(entries: readonly (readonly [string, Exp])[]) => Exp} */
const object = entries => ['{}', entries.map(([key, value]) => [':', key, value])]

/** The refusal of a module, as text. @type {(root: Exp) => string} */
const refusal = root => assertError(generateRuntime(root))

/** The value item alone, after the header and the `use` lines. @type {(rust: string) => string} */
const item = rust => rust.slice(rust.indexOf('/// The runtime as a value'))

export const proof = {
    /**
     * The repository's runtime, from its compiled EDAG: one item, the
     * value, under the generated header and the `use` lines it spells.
     * Every function a section names carries the NativeFunction text of
     * its path — a static, a member — where a helper keeps its body's;
     * `Object.entries` is the closure over `Any::entries` under its own;
     * the intrinsics `found` and `codePointAt` call ask no runtime; and the sections are
     * the three. No static is read and no member called: the module has
     * no runtime in scope, and the printer would refuse either.
     */
    runtime: () => {
        const rust = assertOk(generateRuntime(/** @type {Exp} */ (/** @type {unknown} */ (runtime))))
        for (const line of [
            '// @generated by `npm run gen` from `fjs/js/runtime/module.f.js`. Do not edit: change the runtime and regenerate.',
            'use nanvm_lib::vm::unstable::{f64_any, strict_eq, strict_ne, string_any, string_key};',
            'use nanvm_lib::vm::{Any, Array, IStaticFunction, Nullish, ToAny, ToArray, ToObject};',
            '#[rustfmt::skip]\npub fn runtime<A: IStaticFunction>() -> Result<Any<A>, Any<A>> {',
            'Some("function is() { [native code] }")',
            'Some("function isNaN() { [native code] }")',
            'Some("function isInteger() { [native code] }")',
            'Some("function startsWith() { [native code] }")',
            'A::static_function(|_self, args| Any::entries(args.argument(0)), 1, Array::default(), Some("function entries() { [native code] }")).to_any()',
            'Some("($0)=>$0===0&&1/$0<0")',
            'string_any("slice")).end_call_native(|| Ok([args.argument(1), args.argument(2)].to_array().to_any()))',
            'string_any("charCodeAt")).end_call_native(|| Ok([args.argument(1)].to_array().to_any()))',
            '(string_key("dot"), ',
        ]) {
            assert(rust.includes(line), line)
        }
        assert(!rust.includes('static_read') && !rust.includes('end_call(&') && !rust.includes('IVm'))
        assertEq(rust.split('pub fn ').length, 2)
        // the tagged text resolves, every tag closed
        assertOk(fromTagged(assertOk(generateRuntimeTagged(/** @type {Exp} */ (/** @type {unknown} */ (runtime))))))
    },
    /**
     * A small module, whole: a helper a static captures and a member, each
     * a closure in the value under the NativeFunction text of its path, the
     * helper under its body's, in one `runtime` item.
     */
    small: () => {
        const helper = fn(1, [], ['+', ['arg', 0], 1])
        const inc = fn(1, [helper, 2, ['undefined'], 's'], ['[]', [['()', ['frame', 0], [['arg', 0]]], ['frame', 1], ['frame', 2], ['frame', 3], ['self']]])
        const root = module([
            ['static', object([['Object', object([['inc', inc]])]])],
            ['member', object([['tail', fn(1, [], ['[]', [['arg', 0]]])]])],
        ])
        assertEq(assertOk(generateRuntime(root)), `// @generated by \`npm run gen\` from \`fjs/js/runtime/module.f.js\`. Do not edit: change the runtime and regenerate.

use nanvm_lib::vm::unstable::{f64_any, string_any, string_key};
use nanvm_lib::vm::{Any, Array, Function, IStaticFunction, Nullish, ToAny, ToArray, ToObject};

/// The runtime as a value: the \`runtime\` export of \`fjs/js/runtime\`, its \`static\`, \`member\` and \`dot\`
/// sections, as the ordinary backend prints any module — every built-in a closure carrying the
/// NativeFunction text of its path, \`Object.entries\` the built-in itself. Built once by whoever runs
/// compiled modules and handed to each as its parameter (\`fjs/js/runtime/README.md\`).
#[rustfmt::skip]
pub fn runtime<A: IStaticFunction>() -> Result<Any<A>, Any<A>> {
    let c0: Any<A> = A::static_function(|_self, args| { args.argument(0) + f64_any(0x3ff0000000000000) }, 1, Array::default(), Some("($0)=>$0+1")).to_any();
    let c1: Any<A> = A::static_function(|self_, args| {
        let c0: Any<A> = Any::call(A::frame(self_)[0].clone(), [args.argument(0)].to_array().to_any())?;
        Ok([c0, A::frame(self_)[1].clone(), A::frame(self_)[2].clone(), A::frame(self_)[3].clone(), Function::new(self_.clone()).to_any()].to_array().to_any())
    }, 1, [c0, f64_any(0x4000000000000000), Nullish::Undefined.to_any(), string_any("s")].to_array(), Some("function inc() { [native code] }")).to_any();
    let c2: Any<A> = [(string_key("inc"), c1)].to_object().to_any();
    let c3: Any<A> = [(string_key("Object"), c2)].to_object().to_any();
    let c4: Any<A> = A::static_function(|_self, args| { Ok([args.argument(0)].to_array().to_any()) }, 1, Array::default(), Some("function tail() { [native code] }")).to_any();
    let c5: Any<A> = [(string_key("tail"), c4)].to_object().to_any();
    Ok([(string_key("static"), c3), (string_key("member"), c5)].to_object().to_any())
}
`)
    },
    /**
     * Either section may be absent, and `dot` is a property of the value
     * like the other two; with none, the value is the empty object. A
     * built-in is found through an import's read of its export object,
     * `{ f }.f`, and a module-level value a body captures that is no
     * function — data the runtime holds — is printed as the ordinary
     * backend prints it.
     */
    sections: () => {
        const one = fn(0, [], 1)
        const statics = assertOk(generateRuntime(module([['static', object([['Number', object([['one', one]])]])]])))
        assert(statics.includes('Some("function one() { [native code] }")') && statics.includes('(string_key("Number"), ') && !statics.includes('"member"'))
        const members = assertOk(generateRuntime(module([['member', object([['one', one]])]])))
        assert(members.includes('(string_key("member"), ') && !members.includes('"static"'))
        const none = assertOk(generateRuntime(module([])))
        assert(item(none).includes('pub fn runtime<A: IVm>() -> Result<Any<A>, Any<A>> {\n    Ok(Object::default().to_any())\n}'))
        const withDot = assertOk(generateRuntime(module([['dot', fn(2, [], ['undefined'])]])))
        assert(withDot.includes('(string_key("dot"), c0)') && withDot.includes('Some("($0,$1)=>undefined")'))
        const imported = assertOk(generateRuntime(module([['static', object([['Object', object([['f', ['.', object([['f', one]]), 'f']]])]])]])))
        assert(imported.includes('Some("function f() { [native code] }")'))
        const data = assertOk(generateRuntime(module([['static', object([['Object', object([['f', fn(0, [['[]', [1, 2]]], ['frame', 0])]])]])]])))
        assert(data.includes('[f64_any(0x3ff0000000000000), f64_any(0x4000000000000000)].to_array().to_any()'))
    },
    /**
     * The core may not use what it defines: a body calling a member
     * function, or reading a static function the runtime defines, is
     * refused by the backend, naming the step or the static, since the
     * module has no runtime in scope — where the native static
     * `Object.entries`, which the `static` section lists as itself, is the
     * closure the value holds, and an intrinsic's helper asks no runtime.
     */
    core: () => {
        const member = module([['static', object([['Object', object([['f', fn(1, [], ['.', ['arg', 0], 'slice', ['|()', [1]]])]])]])]])
        assert(refusal(member).startsWith('a member call with no runtime in scope; the core may not use what it defines: '))
        const guarded = module([['member', object([['f', fn(1, [], ['?.', ['arg', 0], 'at', ['|?.()', [1]]])]])]])
        assert(refusal(guarded).startsWith('a member call with no runtime in scope; the core may not use what it defines: '))
        const nested = module([['static', object([['Object', object([['f', fn(0, [], fn(1, [], ['.', ['arg', 0], 'slice', ['|()', [1]]]))]])]])]])
        assert(refusal(nested).startsWith('a member call with no runtime in scope; the core may not use what it defines: '))
        assertEq(refusal(module([['static', object([['Object', object([['f', fn(0, [], ['Number.isNaN'])]])]])]])), 'a static function read with no runtime in scope; the core may not use what it defines: Number.isNaN')
        assertEq(refusal(module([['static', object([['Object', object([['f', fn(0, [['Object.is']], ['frame', 0])]])]])]])), 'a static function read with no runtime in scope; the core may not use what it defines: Object.is')
        const listed = assertOk(generateRuntime(module([['static', object([['Object', object([['entries', ['Object.entries']]])]])]])))
        assert(listed.includes('(string_key("entries"), c0)') && listed.includes('Any::entries(args.argument(0))'))
        const read = assertOk(generateRuntime(module([['static', object([['Object', object([['f', fn(0, [['Object.entries']], ['frame', 0])]])]])]])))
        assert(read.includes('Any::entries(args.argument(0))'))
        const slice = assertOk(generateRuntime(module([['member', object([['f', fn(1, [['slice']], ['()', ['frame', 0], [['arg', 0], 1]])]])]])))
        assert(slice.includes('.end_call_native('))
        // a value's own property read is no member call
        assert(assertOk(generateRuntime(module([['member', object([['f', fn(1, [], ['.', ['arg', 0], 'length'])]])]]))).includes('string_any("length")).end()'))
    },
    /**
     * Refused before the backend sees the module: a module without the
     * `runtime` export or with another beside it, a section or a namespace
     * that is no object, a built-in that is no function, a body under a
     * path every executor binds natively, a `dot` that is no function, and
     * one function two built-ins name, which JavaScript keeps apart and
     * which could carry only one text.
     */
    refusals: () => {
        assert(refusal(['{}', []]).startsWith('no `runtime` export of objects: '))
        assert(refusal(['{}', [[':', 'runtime', 1]]]).startsWith('no `runtime` export of objects: '))
        assert(refusal(['[]', []]).startsWith('no `runtime` export of objects: '))
        assertEq(refusal(['{}', [[':', 'runtime', object([])], [':', 'x', 1], [':', 'y', 2]]]), 'the runtime module exports `runtime` alone: x,y')
        assertEq(refusal(module([['static', 1]])), 'a section of the runtime that is no object: 1')
        assertEq(refusal(module([['member', 1]])), 'a section of the runtime that is no object: 1')
        assertEq(refusal(module([['static', object([['String', 1]])]])), 'a namespace of the runtime that is no object: String')
        assertEq(refusal(module([['static', object([['Object', object([['x', 1]])]])]])), 'a built-in that is no function: Object.x')
        assertEq(refusal(module([['member', object([['x', ['.', object([['x', 1]]), 'x']]])]])), 'a built-in that is no function: x')
        assertEq(refusal(module([['member', object([['x', ['.', ['[]', []], 'x']]])]])), 'a built-in that is no function: x')
        assertEq(refusal(module([['member', object([['x', ['.', object([['y', 1]]), 'x']]])]])), 'a built-in that is no function: x')
        assertEq(refusal(module([['static', object([['Object', object([['is', ['Object.is']]])]])]])), 'a built-in that is no function: Object.is')
        assertEq(refusal(module([['static', object([['Object', ['{}', [['...', object([])]]]]])]])), 'a namespace of the runtime that is no object: Object')
        assertEq(refusal(module([['static', object([['Object', object([['entries', fn(1, [], 1)]])]])]])), 'a body for a static every executor binds natively: Object.entries')
        assertEq(refusal(module([['dot', 'x']])), 'a `dot` section that is no function: x')
        assertEq(refusal(module([['dot', object([])]])), 'a `dot` section that is no function: {},')
        const shared = fn(0, [], 1)
        assertEq(refusal(module([['static', object([['Number', object([['isNaN', shared]])], ['Global', object([['isNaN', shared]])]])]])), 'a function two built-ins name; JavaScript keeps them apart: Global.isNaN')
        assertEq(refusal(module([['static', object([['Object', object([['is', shared]])]])], ['member', object([['is', shared]])]])), 'a function two built-ins name; JavaScript keeps them apart: is')
        // a property written twice keeps its last value, as the EDAG means
        // it, and is one built-in
        assert(assertOk(generateRuntime(module([['static', object([['Object', object([['g', fn(0, [], 1)], ['g', fn(0, [], 7)]])]])]]))).includes('f64_any(0x401c000000000000)'))
    },
}
